-- SmartStock — Inventory Management System
-- Script: 01_create_schema.sql
-- Description: DDL script to create CATEGORIES, SUPPLIERS, PRODUCTS, and STOCK_MOVEMENTS
-- Target DB: Oracle Database 19c / 21c / 23ai / 26ai
-- ============================================================================

-- Drop existing tables (if any)
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN ('STOCK_MOVEMENTS', 'PRODUCTS', 'SUPPLIERS', 'CATEGORIES')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE "' || t.table_name || '" CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 1. CATEGORIES TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE CATEGORIES (
    CATEGORY_ID   NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION   VARCHAR2(255),
    CREATED_AT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_CATEGORY_NAME UNIQUE (CATEGORY_NAME)
);

-- ----------------------------------------------------------------------------
-- 2. SUPPLIERS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE SUPPLIERS (
    SUPPLIER_ID   NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    SUPPLIER_NAME VARCHAR2(150) NOT NULL,
    PHONE         VARCHAR2(30),
    EMAIL         VARCHAR2(100),
    ADDRESS       VARCHAR2(300),
    CREATED_AT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_SUP_EMAIL CHECK (EMAIL IS NULL OR EMAIL LIKE '%_@__%.__%')
);

-- ----------------------------------------------------------------------------
-- 3. PRODUCTS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE PRODUCTS (
    PRODUCT_ID      NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    SKU             VARCHAR2(50) NOT NULL,
    PRODUCT_NAME    VARCHAR2(150) NOT NULL,
    CATEGORY_ID     NUMBER NOT NULL,
    SUPPLIER_ID     NUMBER,
    PURCHASE_PRICE  NUMBER(12,2) NOT NULL,
    SELLING_PRICE   NUMBER(12,2) NOT NULL,
    QUANTITY        NUMBER(10) DEFAULT 0 NOT NULL,
    MIN_STOCK_LEVEL NUMBER(10) DEFAULT 5 NOT NULL,
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_PRODUCT_SKU UNIQUE (SKU),
    CONSTRAINT FK_PROD_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID),
    CONSTRAINT FK_PROD_SUPPLIER FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIERS(SUPPLIER_ID),
    CONSTRAINT CHK_PURCHASE_PRICE CHECK (PURCHASE_PRICE >= 0),
    CONSTRAINT CHK_SELLING_PRICE CHECK (SELLING_PRICE >= 0),
    CONSTRAINT CHK_PRODUCT_QTY CHECK (QUANTITY >= 0),
    CONSTRAINT CHK_MIN_STOCK CHECK (MIN_STOCK_LEVEL >= 0),
    CONSTRAINT CHK_PROD_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

-- ----------------------------------------------------------------------------
-- 4. STOCK_MOVEMENTS TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE STOCK_MOVEMENTS (
    MOVEMENT_ID       NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    PRODUCT_ID        NUMBER NOT NULL,
    MOVEMENT_TYPE     VARCHAR2(20) NOT NULL,
    QUANTITY          NUMBER(10) NOT NULL,
    PREVIOUS_QUANTITY NUMBER(10) NOT NULL,
    NEW_QUANTITY      NUMBER(10) NOT NULL,
    REFERENCE_NUMBER  VARCHAR2(100),
    REMARKS           VARCHAR2(400),
    CREATED_AT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_MOV_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT CHK_MOV_TYPE CHECK (MOVEMENT_TYPE IN ('STOCK_IN', 'STOCK_OUT')),
    CONSTRAINT CHK_MOV_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CHK_PREV_QTY CHECK (PREVIOUS_QUANTITY >= 0),
    CONSTRAINT CHK_NEW_QTY CHECK (NEW_QUANTITY >= 0)
);

-- ----------------------------------------------------------------------------
-- 5. INDEXES FOR PERFORMANCE
-- ----------------------------------------------------------------------------
CREATE INDEX IDX_PROD_CAT ON PRODUCTS(CATEGORY_ID);
CREATE INDEX IDX_PROD_SUP ON PRODUCTS(SUPPLIER_ID);
CREATE INDEX IDX_PROD_STATUS ON PRODUCTS(STATUS);
CREATE INDEX IDX_MOV_PROD ON STOCK_MOVEMENTS(PRODUCT_ID);
CREATE INDEX IDX_MOV_TYPE ON STOCK_MOVEMENTS(MOVEMENT_TYPE);
CREATE INDEX IDX_MOV_DATE ON STOCK_MOVEMENTS(CREATED_AT DESC);
